classdef ExportSimulationComparisonPlotsTest < matlab.unittest.TestCase
    %ExportSimulationComparisonPlotsTest Tests the public export API.
    % Copyright 2026 The MathWorks, Inc.

    properties (TestParameter)
        InvalidSelection = struct( ...
            MissingFields=struct("Other", 1), ...
            ZeroId=struct("EntryId", 0, "Subscripts", 1), ...
            FractionalId=struct("EntryId", 1.5, "Subscripts", 1), ...
            InfiniteId=struct("EntryId", Inf, "Subscripts", 1), ...
            TextId=struct("EntryId", "1", "Subscripts", 1), ...
            EmptySubscripts=struct("EntryId", 1, "Subscripts", []), ...
            FractionalSubscripts=struct("EntryId", 1, "Subscripts", 1.5), ...
            ColumnSubscripts=struct("EntryId", 1, "Subscripts", [1; 1]), ...
            InvalidInterpretation=struct("EntryId", 1, "Subscripts", 1, ...
            "SignalInterpretation", "unknown"))
        InvalidXLimits = struct(Equal=[1, 1], Reversed=[2, 1], ...
            Infinite=[0, Inf], Mixed=[NaN, 1])
        FormatAlias = struct( ...
            JPEG=struct("Format", " JPEG ", "Extension", ".jpg"), ...
            TIFF=struct("Format", "tiff", "Extension", ".tif"))
        OutputFormat = struct( ...
            PNG="png", ...
            JPEG="jpg", ...
            TIFF="tif", ...
            PDF="pdf", ...
            SVG="svg")
    end

    methods (TestClassSetup)
        function disableWarnings(testCase)
            import matlab.unittest.fixtures.SuppressedWarningsFixture

            % Delegate to SuppressedWarningsFixture to suppress display of warnings.
            testCase.applyFixture(SuppressedWarningsFixture('MATLAB:hg:AutoSoftwareOpenGL'));
            testCase.applyFixture(SuppressedWarningsFixture('MATLAB:handle_graphics:exceptions:SceneNode'));
        end
    end

    methods (Test)
        function testRejectsInvalidSelections(testCase, InvalidSelection)
            model = simcompare.Models.ComparisonModel();
            testCase.addTeardown(@delete, model);

            testCase.verifyError( ...
                @() simcompare.Exporters.ComparisonPlotExporter.export( ...
                model, InvalidSelection, OutputFolder=string(tempname)), ...
                "simcompare:Export:InvalidSelection");
        end

        function testRejectsEmptySelection(testCase)
            model = simcompare.Models.ComparisonModel();
            testCase.addTeardown(@delete, model);

            testCase.verifyError( ...
                @() simcompare.Exporters.ComparisonPlotExporter.export( ...
                model, struct.empty(1, 0), OutputFolder=string(tempname)), ...
                "simcompare:Export:NoSignals");
        end

        function testRejectsInvalidXLimits(testCase, InvalidXLimits)
            files = createDatasetPair(testCase);
            recorder = testsupport.IssueReportRecorder();

            testCase.verifyError(@() exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, ...
                OutputFolder=files.Folder, XLimits=InvalidXLimits, ...
                IssueReporter=@recorder.report), ...
                "simcompare:Export:InvalidXLimits");
            testCase.verifyEqual(recorder.Count, 1);
        end

        function testRejectsBlankOutputFolder(testCase)
            files = createDatasetPair(testCase);
            recorder = testsupport.IssueReportRecorder();

            testCase.verifyError(@() exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, OutputFolder=" ", ...
                IssueReporter=@recorder.report), ...
                "simcompare:Export:EmptyOutputFolder");
        end

        function testRejectsOutputPathThatIsAFile(testCase)
            files = createDatasetPair(testCase);
            recorder = testsupport.IssueReportRecorder();
            originalData = load(files.Baseline);

            testCase.verifyError(@() exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, OutputFolder=files.Baseline, ...
                IssueReporter=@recorder.report), ...
                "simcompare:Export:OutputIsFile");
            testCase.verifyEqual(load(files.Baseline), originalData);
        end

        function testExportsAllSignalsByDefault(testCase)
            files = createDatasetPair(testCase);

            exported = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, OutputFolder=files.Folder);

            [~, names] = fileparts(exported);
            testCase.verifyEqual(names, ["scalar"; "vector_element_1"]);
            testCase.verifyTrue(all(isfile(exported)));
        end

        function testRepeatedSignalNamesExportOnce(testCase)
            files = createDatasetPair(testCase);

            exported = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, Signals=["vector", "scalar", "vector"], ...
                OutputFolder=files.Folder);

            [~, names] = fileparts(exported);
            testCase.verifyEqual(names, ["vector_element_1"; "scalar"]);
        end

        function testRejectsEmptySignalName(testCase)
            files = createDatasetPair(testCase);
            recorder = testsupport.IssueReportRecorder();

            testCase.verifyError(@() exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, Signals=["scalar", ""], ...
                OutputFolder=files.Folder, IssueReporter=@recorder.report), ...
                "simcompare:Export:EmptySignalName");
        end

        function testNormalizesFormatAliases(testCase, FormatAlias)
            files = createDatasetPair(testCase);

            exported = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, Signals="scalar", ...
                OutputFolder=files.Folder, Format=FormatAlias.Format);

            [~, ~, extension] = fileparts(exported);
            testCase.verifyEqual(extension, FormatAlias.Extension);
            testCase.verifyTrue(isfile(exported));
        end

        function testRelativeOutputFolderReturnsAbsoluteFiles(testCase)
            files = createDatasetPair(testCase);
            testCase.applyFixture(matlab.unittest.fixtures.CurrentFolderFixture(files.Folder));

            exported = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, Signals="scalar", OutputFolder="nested/exports");

            testCase.verifyEqual(exported, fullfile(files.Folder, "nested", "exports", "scalar.png"));
            testCase.verifyTrue(isfile(exported));
        end

        function testExportsEachSupportedFormat(testCase, OutputFormat)
            files = createDatasetPair(testCase);
            outputFolder = fullfile( ...
                files.Folder, "exports-" + OutputFormat);

            exported = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, ...
                Signals="scalar", ...
                OutputFolder=outputFolder, ...
                Format=OutputFormat);

            fileInfo = dir(exported);
            [~, ~, extension] = fileparts(exported);
            testCase.verifyTrue(isfolder(outputFolder));
            testCase.verifyTrue(isfile(exported));
            testCase.verifyGreaterThan(fileInfo.bytes, 0);
            testCase.verifyEqual(string(extension), "." + OutputFormat);
        end

        function testExportsOnlySelectedSignalsToOneFolder(testCase)
            files = createDatasetPair(testCase);
            outputFolder = fullfile(files.Folder, "selected");

            exported = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, ...
                Signals=["scalar", "vector"], ...
                OutputFolder=outputFolder, ...
                Format="png");

            [~, names] = fileparts(exported);
            listing = dir(fullfile(outputFolder, "*.png"));
            testCase.verifyEqual(numel(exported), 2);
            testCase.verifyEqual(numel(listing), 2);
            testCase.verifyEqual( ...
                string(names), ["scalar"; "vector_element_1"]);
            testCase.verifyTrue(all(isfile(exported)));
        end

        function testUnknownSignalIsRejected(testCase)
            files = createDatasetPair(testCase);
            recorder = testsupport.IssueReportRecorder();

            testCase.verifyError(@() exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, ...
                Signals="missing", ...
                OutputFolder=fullfile(files.Folder, "exports"), ...
                IssueReporter=@recorder.report), ...
                "simcompare:Export:SignalNotFound");
            testCase.verifyEqual(recorder.Count, 1);
            testCase.verifyEqual( ...
                recorder.ExceptionIdentifier, ...
                "simcompare:Export:SignalNotFound");
            testCase.verifyEqual( ...
                recorder.Context, ...
                "CLI: exportSimulationComparisonPlots");
        end

        function testExistingExportIsNotOverwritten(testCase)
            files = createDatasetPair(testCase);
            outputFolder = fullfile(files.Folder, "repeat");
            first = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, ...
                Signals="scalar", ...
                OutputFolder=outputFolder, ...
                Format="png");

            second = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, ...
                Signals="scalar", ...
                OutputFolder=outputFolder, ...
                Format="png");

            [~, firstName] = fileparts(first);
            [~, secondName] = fileparts(second);
            testCase.verifyEqual(string(firstName), "scalar");
            testCase.verifyEqual(string(secondName), "scalar_2");
            testCase.verifyTrue(all(isfile([first; second])));
        end

        function testAcceptsCustomLegendText(testCase)
            files = createDatasetPair(testCase);

            exported = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, ...
                Signals="scalar", ...
                OutputFolder=fullfile(files.Folder, "custom-legend"), ...
                BaselineLegendText="Reference", ...
                CompareLegendText="Candidate");

            testCase.verifyTrue(isfile(exported));
        end

        function testExportsAbsoluteError(testCase)
            files = createDatasetPair(testCase);

            exported = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, ...
                Signals="scalar", ...
                OutputFolder=fullfile( ...
                files.Folder, "absolute-error"), ...
                ErrorType="Absolute");

            testCase.verifyTrue(isfile(exported));
        end

        function testExportsFlattenedVirtualBusLeaf(testCase)
            files = createBusDatasetPair(testCase);
            outputFolder = fullfile(files.Folder, "bus-export");
            signalNames = [ ...
                "NonVirtualBus.Controller.Measurements.Scalar", ...
                "VirtualBus.Controller.Measurements.Scalar"];

            exported = exportSimulationComparisonPlots( ...
                files.Baseline, files.Compare, ...
                Signals=signalNames, ...
                OutputFolder=outputFolder);

            [~, name, extension] = fileparts(exported);
            testCase.verifyEqual( ...
                string(name) + string(extension), ...
                signalNames.' + ".png");
            testCase.verifyTrue(all(isfile(exported)));
        end
    end
end

function files = createDatasetPair(testCase)
folder = string(tempname);
mkdir(folder);
testCase.addTeardown(@() rmdir(folder, "s"));
baselineFile = fullfile(folder, "baseline.mat");
compareFile = fullfile(folder, "compare.mat");
time = [0; 1; 2];
baseline = { ...
    testsupport.spec("scalar", time, [1; 2; 3]), ...
    testsupport.spec("vector", time, ...
    [1, 10; 2, 20; 3, 30])};
comparison = { ...
    testsupport.spec("scalar", time, [1; 2; 4]), ...
    testsupport.spec("vector", time, ...
    [2, 11; 3, 21; 4, 31])};
testsupport.createDatasetFile(baselineFile, "logs", baseline);
testsupport.createDatasetFile(compareFile, "logs", comparison);
files = struct( ...
    "Folder", folder, ...
    "Baseline", baselineFile, ...
    "Compare", compareFile);
end

function files = createBusDatasetPair(testCase)
folder = string(tempname);
mkdir(folder);
testCase.addTeardown(@() rmdir(folder, "s"));
baselineFile = fullfile(folder, "baseline.mat");
compareFile = fullfile(folder, "compare.mat");
testsupport.createBusDatasetFile( ...
    baselineFile, "baselineLogs", 1);
testsupport.createBusDatasetFile( ...
    compareFile, "compareLogs", 2);
files = struct( ...
    "Folder", folder, ...
    "Baseline", baselineFile, ...
    "Compare", compareFile);
end
