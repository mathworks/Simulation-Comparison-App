classdef IssueReporter
    %IssueReporter Offer to create a prefilled GitHub issue for an error.
    % Copyright 2026 The MathWorks, Inc.

    properties (Constant)
        ProjectURL = ...
            "https://github.com/mathworks/Simulation-Comparison-App"
    end

    methods (Static)
        function opened = prompt(exception, context, parentFigure, options)
            arguments
                exception (1, 1) MException
                context (1, 1) string = "Simulation Comparison App"
                parentFigure = []
                options.PromptFcn (1, 1) function_handle = ...
                    @presentIssuePrompt
                options.UrlOpener (1, 1) function_handle = @openIssuePage
            end

            opened = false;
            message = promptMessage(exception);
            selection = string(options.PromptFcn(parentFigure, message));
            if selection ~= "Report issue"
                return
            end

            issueURL = simcompare.IssueReporter.buildIssueURL( ...
                exception, context);
            options.UrlOpener(issueURL);
            opened = true;
        end

        function notify(reporter, exception, context, parentFigure)
            arguments
                reporter (1, 1) function_handle
                exception (1, 1) MException
                context (1, 1) string
                parentFigure = []
            end

            try
                reporter(exception, context, parentFigure);
            catch reportingException
                warning("simcompare:IssueReporter:Failed", ...
                    "Could not offer issue reporting: %s", ...
                    reportingException.message);
            end
        end

        function issueURL = buildIssueURL(exception, context)
            arguments
                exception (1, 1) MException
                context (1, 1) string = "Simulation Comparison App"
            end

            parameters = [ ...
                matlab.net.QueryParameter( ...
                "template", "bug_report.md"), ...
                matlab.net.QueryParameter( ...
                "title", issueTitle(exception, context)), ...
                matlab.net.QueryParameter( ...
                "body", issueDescription( ...
                exception, context))];
            uri = matlab.net.URI( ...
                simcompare.IssueReporter.ProjectURL + "/issues/new", ...
                parameters);
            issueURL = string(uri.EncodedURI);
        end
    end
end

function message = promptMessage(exception)
errorMessage = singleLineMessage(exception);
if strlength(errorMessage) > 600
    errorMessage = extractBefore(errorMessage, 601) + "…";
end
message = "MATLAB encountered an error:" + newline + newline + ...
    errorMessage + newline + newline + ...
    "Would you like to open a prefilled GitHub issue? " + ...
    "The draft includes diagnostic details and can be reviewed " + ...
    "before submission.";
end

function selection = presentIssuePrompt(parentFigure, message)
if ~isempty(parentFigure) && isvalid(parentFigure)
    selection = uiconfirm( ...
        parentFigure, message, "Report MATLAB Error", ...
        Options=["Report issue", "Not now"], ...
        DefaultOption=1, ...
        CancelOption=2, ...
        Icon="error");
elseif desktop("-inuse")
    selection = questdlg( ...
        message, "Report MATLAB Error", ...
        "Report issue", "Not now", "Report issue");
else
    warning("simcompare:IssueReporter:PromptUnavailable", ...
        "%s", message);
    selection = "Not now";
end
selection = string(selection);
end

function openIssuePage(issueURL)
web(issueURL, "-browser");
end

function title = issueTitle(exception, context)
title = "MATLAB error";
if strlength(context) > 0
    title = title + " in " + context;
end
message = singleLineMessage(exception);
if strlength(message) > 0
    title = title + ": " + message;
end
if strlength(title) > 200
    title = extractBefore(title, 200) + "…";
end
end

function description = issueDescription(exception, context)
identifier = string(exception.identifier);
if strlength(identifier) == 0
    identifier = "unidentified";
end
report = string(getReport(exception, "extended", "hyperlinks", "off"));
report = replace(report, "```", "'''");
if strlength(report) > 5000
    report = extractBefore(report, 5001) + ...
        newline + "[Diagnostic report truncated]";
end

description = strjoin([ ...
    "## MATLAB error"; ...
    ""; ...
    "- **Type:** MATLAB error"; ...
    "- **Identifier:** `" + identifier + "`"; ...
    "- **Context:** " + context; ...
    "- **App version:** " + string(simcompare.toolboxVersion()); ...
    "- **MATLAB:** " + string(version); ...
    "- **Platform:** " + string(computer); ...
    "- **Occurred:** " + string(datetime("now", ...
    TimeZone="local", Format="yyyy-MM-dd HH:mm:ss Z")); ...
    ""; ...
    "## Diagnostic report"; ...
    ""; ...
    "```text"; ...
    report; ...
    "```"; ...
    ""; ...
    "## Steps to reproduce"; ...
    ""; ...
    "1. "; ...
    ""; ...
    "## Additional information"; ...
    ""], ...
    newline);
end

function message = singleLineMessage(exception)
message = regexprep(strtrim(string(exception.message)), "\s+", " ");
end
