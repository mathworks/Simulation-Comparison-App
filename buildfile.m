function plan = buildfile
%buildfile Build, test, measure, and package Simulation Comparison App.
% Copyright 2026 The MathWorks, Inc.

import matlab.buildtool.tasks.*
import matlab.automation.Verbosity

plan = buildplan(localfunctions);

% CleanTask removes declared outputs and the buildtool incremental cache.
plan("clean") = CleanTask;

% Treat all Code Analyzer warnings as build failures.
plan("check") = CodeIssuesTask("toolbox", ...
    WarningThreshold=0, ...
    Results="results/code-issues.sarif");

% Keep test source scopes narrow so incremental builds rerun only the
% affected application layer. Each task writes separate artifacts;
% coverageTask combines the coverage results for CI reporting.
modelTest = TestTask([ ...
    "tests/ComparisonModelTest.m", ...
    "tests/ReleaseCheckerTest.m"], ...
    SourceFiles= "toolbox/+simcompare/+Models", ...
    OutputDetail="Detailed", ...
    Strict=true, ...
    TestResults="results/test-results-model.xml") ...
    .addCodeCoverage("results/coverage-model.mat");

viewModelTest = TestTask("tests/MainViewModelTest.m", ...
    SourceFiles="toolbox/+simcompare/+ViewModels", ...
    OutputDetail="Detailed", ...
    Strict=true, ...
    TestResults="results/test-results-view-model.xml") ...
    .addCodeCoverage("results/coverage-view-model.mat");

exportTest = TestTask("tests/ExportSimulationComparisonPlotsTest.m", ...
    SourceFiles=["toolbox/exportSimulationComparisonPlots.m", ...
    "toolbox/+simcompare/+Exporters"], ...
    OutputDetail="Detailed", ...
    Strict=true, ...
    TestResults="results/test-results-export.xml") ...
    .addCodeCoverage("results/coverage-export.mat");

appTest = TestTask([ ...
    "tests/SimulationComparisonAppTest.m", ...
    "tests/IssueReporterTest.m"], ...
    SourceFiles=["toolbox/runSimulationComparisonApp.m", ...
    "toolbox/+simcompare/IssueReporter.m", ...
    "toolbox/+simcompare/toolboxVersion.m", ...
    "toolbox/+simcompare/+Views"], ...
    OutputDetail="Detailed", ...
    Strict=true, ...
    TestResults="results/test-results-app.xml") ...
    .addCodeCoverage("results/coverage-app.mat");

testTasks = [modelTest, viewModelTest, exportTest, appTest];

plan("test") = matlab.buildtool.TaskGroup(testTasks, ...
    TaskNames=["model", "view-model", "export", "app"], ...
    Description="Run incremental tests by application layer", ...
    Dependencies="check");

% Coverage reporting is advisory and runs after tests.
plan("coverage").Description = ...
    "Report statement coverage with an advisory 80% threshold";
plan("coverage").Dependencies = "test";
plan("coverage").Inputs = "results/coverage-*.mat";
plan("coverage").Outputs = "results/coverage.xml";

% Packaging is explicit and receives its version at invocation time.
plan("package").Description = ...
    "Package the app using a required matlab.mpm.Version argument";
plan("package").Dependencies = ["coverage" "test"];
plan("package").DisableIncremental = true;

% A bare buildtool invocation performs all quality checks and coverage.
plan.DefaultTasks = ["check", "test", "coverage"];
end

function coverageTask(context)
%coverageTask Report statement coverage without failing below the threshold.

coverageFiles = fullfile( ...
    context.Plan.RootFolder, coverageResultFiles());
if ~all(isfile(coverageFiles))
    context.log("Coverage data not found; run the test task first.");
    return
end

coverageResult = matlab.coverage.Result.empty;
for coverageFile = coverageFiles
    coverageData = load(coverageFile);
    coverageResult = [coverageResult; coverageData.coverage(:)]; %#ok<AGROW>
end
[summary, description] = coverageSummary( ...
    coverageResult, "statement");
lineRate = sum(summary(:, 1)) / sum(summary(:, 2));
context.log(sprintf("Statement coverage: %.1f%%", lineRate * 100));

for index = 1:size(summary, 1)
    [~, name, extension] = fileparts( ...
        description(index).statement(1).Filename);
    context.log(sprintf("  %s%s: %d/%d statements", ...
        name, extension, summary(index, 1), summary(index, 2)));
end

threshold = 0.80;
if lineRate < threshold
    context.log(sprintf( ...
        "WARNING: Coverage %.1f%% is below the advisory %.0f%% threshold.", ...
        lineRate * 100, threshold * 100));
end
generateCoberturaReport(coverageResult, fullfile( ...
    context.Plan.RootFolder, "results", "coverage.xml"));
end

function files = coverageResultFiles()
files = [ ...
    "results/coverage-model.mat", ...
    "results/coverage-view-model.mat", ...
    "results/coverage-export.mat", ...
    "results/coverage-app.mat"];
end

function packageTask(context, version)
%packageTask Package the toolbox using a release-supplied semantic version.

arguments
    context
    version (1, 1) string {mustBeTextScalar}
end

version = matlab.mpm.Version(erase(version, "v"));
versionText = string(version);

context.assertTrue( ...
    isempty(version.Prerelease) && isempty(version.Build), ...
    "Toolbox versions cannot contain prerelease or build metadata.");

versionFile = fullfile( ...
    context.Plan.RootFolder, "toolbox", "+simcompare", ...
    "toolboxVersion.m");
originalVersionFile = readFileBytes(versionFile);
versionFileCleanup = onCleanup( ...
    @() writeFileBytes(versionFile, originalVersionFile));
writeToolboxVersionFile(versionFile, versionText);

options = matlab.addons.toolbox.ToolboxOptions( ...
    "toolbox", "c60077af-5691-44a7-b481-795f58dca71d", ...
    ToolboxName="Simulation Comparison App", ...
    ToolboxVersion=versionText, ...
    Summary="Compare signals from MAT-files or SDI runs.", ...
    Description="Interactively align matching SimulationData Dataset " + ...
    "signals from MAT-files, current SDI runs, or saved SDI sessions, " + ...
    "select multidimensional elements, and inspect relative or absolute " + ...
    "error.", ...
    AppGalleryFiles=fullfile("toolbox", "runSimulationComparisonApp.m"), ...
    ToolboxGettingStartedGuide=fullfile("toolbox", "doc", "GettingStarted.m"), ...
    AuthorName = 'Pablo Romero', ...
    AuthorEmail = "promero@mathworks.com", ...
    AuthorCompany = "The MathWorks", ...
    MinimumMatlabRelease="R2024b");

packageName = "Simulation_Comparison_App_v" + ...
    versionText + ".mltbx";
options.OutputFile = fullfile("release", packageName);
matlab.addons.toolbox.packageToolbox(options);

context.assertTrue(isfile(options.OutputFile), ...
    "The toolbox package was not created.");
packageInfo = dir(options.OutputFile);
context.log(sprintf("Package: %s v%s (%.1f KB)", ...
    options.OutputFile, versionText, packageInfo.bytes / 1024));
end

function writeToolboxVersionFile(filePath, version)
%writeToolboxVersionFile Stamp the runtime version into MATLAB source.

template = ...
    "function version = toolboxVersion\n" + ...
    "%%toolboxVersion Return the version embedded in the packaged toolbox.\n" + ...
    "\n" + ...
    "version = matlab.mpm.Version(""%s"");\n" + ...
    "end\n";
contents = sprintf(template, version);
writeFileBytes(filePath, unicode2native(contents, "UTF-8"));
end

function contents = readFileBytes(filePath)
%readFileBytes Read a file without changing its encoding or line endings.

[fileID, message] = fopen(filePath, "rb");
assert(fileID >= 0, message);
fileCleanup = onCleanup(@() fclose(fileID));
contents = fread(fileID, Inf, "*uint8");
end

function writeFileBytes(filePath, contents)
%writeFileBytes Write bytes to a file, replacing its contents.

[fileID, message] = fopen(filePath, "wb");
assert(fileID >= 0, message);
fileCleanup = onCleanup(@() fclose(fileID));
fwrite(fileID, contents, "uint8");
end
